import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { Resvg } from "@resvg/resvg-js"

const root = fileURLToPath(new URL("..", import.meta.url))
const SCALES = [1, 2, 3]

// The web's tiles (apps/web/src/presentation/atoms/motif/motif.tsx): height in dp per variant.
const MOTIFS = {
    kowhaiwhai: { field: ["kowhaiwhai", 38], band: ["kowhaiwhai", 15] },
    raranga: { field: ["raranga", 34], band: ["raranga", 22] },
    puhoro: { field: ["puhoro", 108], band: ["puhoro-band", 16] },
    tapa1: { field: ["tapa1", 30], band: ["tapa1", 13] },
    tapa2: { field: ["tapa2", 40], band: ["tapa2", 16] },
    tapa3: { field: ["tapa3", 34], band: ["tapa3", 14] },
    tapa4: { field: ["tapa4", 44], band: ["tapa4", 18] },
}

function render(svg, height) {
    return new Resvg(svg, { fitTo: { mode: "height", value: height } }).render().asPng()
}

function suffix(scale) {
    return scale === 1 ? "" : `@${scale}x`
}

const imports = []
const entries = []
for (const [motif, variants] of Object.entries(MOTIFS)) {
    const tiles = []
    for (const [variant, [file, height]] of Object.entries(variants)) {
        const svg = readFileSync(`${root}design-system/motifs/${file}.svg`)
        for (const scale of SCALES) {
            writeFileSync(`${root}assets/motifs/${motif}-${variant}${suffix(scale)}.png`, render(svg, height * scale))
        }
        const name = `${motif}${variant[0].toUpperCase()}${variant.slice(1)}`
        imports.push(`import ${name} from "@/assets/motifs/${motif}-${variant}.png"`)
        tiles.push(`${variant}: { source: ${name}, height: ${height} }`)
    }
    entries.push(`    ${motif}: { ${tiles.join(", ")} },`)
}

writeFileSync(
    `${root}src/presentation/atoms/motif/tiles.generated.ts`,
    `// Generated by \`pnpm assets\` (scripts/render-assets.mjs): edit that, not this.
import type { MotifKey } from "@pinai/domain/models/user-settings"
${imports.join("\n")}

export const TILES = {
${entries.join("\n")}
} satisfies Record<MotifKey, Record<"field" | "band", { source: number; height: number }>>
`,
)
